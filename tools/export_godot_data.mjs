// Export what the Godot build needs from the web build's data: the points of
// interest (names and blurbs) per Blender model, and where each model sits.
//   node tools/export_godot_data.mjs      -> godot/data/sites.json
import { writeFileSync, readFileSync } from 'node:fs';
import * as D from '../js/data.js';
import { terrainHeight } from '../js/terrain.js';
const P = D.PYRAMIDS;
const pois = list => list.map(([key, name, blurb, radius]) => ({ key, name, blurb, radius }));
const kc = P.khufu.center, o = D.KHUFU_UPPER.origin, mc = D.MERESANKH.center;
const out = {
  note: 'AUTO-GENERATED by tools/export_godot_data.mjs. Positions are web-build world metres: x east, y up, z south.',
  models: [
    { id: 'khufu_lower', file: 'khufu_lower.glb', title: 'Great Pyramid',
      position: [kc.x, P.khufu.baseY, kc.z], pois: pois(D.KHUFU_LOWER.pois) },
    { id: 'khufu_upper', file: 'khufu_upper.glb', title: 'Great Pyramid — Grand Gallery and King\'s Chamber',
      position: [kc.x + o.x, o.y, kc.z + o.z], pois: pois(D.KHUFU_UPPER.pois) },
    { id: 'menkaure', file: 'menkaure.glb', title: 'Pyramid of Menkaure — substructure',
      position: [P.menkaure.center.x, P.menkaure.baseY, P.menkaure.center.z], pois: pois(D.MENKAURE_SUB.pois) },
    { id: 'meresankh', file: 'meresankh.glb', title: 'Tomb of Queen Meresankh III',
      position: [mc.x - 1.7, terrainHeight(mc.x, mc.z) - 7.5, mc.z + 3.55], pois: pois(D.MERESANKH.pois) },
    { id: 'serapeum', file: 'serapeum.glb', title: 'Serapeum of Saqqara',
      position: [D.SERAPEUM.origin.x, D.SERAPEUM.origin.y, D.SERAPEUM.origin.z], pois: pois(D.SERAPEUM.pois) }
  ]
};
writeFileSync(new URL('../godot/data/sites.json', import.meta.url), JSON.stringify(out, null, 1));
console.log('sites.json:', out.models.map(m => `${m.id} (${m.pois.length} pois)`).join(', '));
